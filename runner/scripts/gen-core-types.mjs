// Generates packages/shared/src/generated/core-openapi.ts from the core's
// contract, api/openapi.draft.json, with the same openapi-typescript version
// and options as web/scripts/api-schema.mjs.
//   npm run gen:core                          write the file
//   node scripts/gen-core-types.mjs --check   fail if the committed file has drifted
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const source = new URL('../../api/openapi.draft.json', import.meta.url);
const target = new URL('../packages/shared/src/generated/core-openapi.ts', import.meta.url);
const check = process.argv.includes('--check');

const ast = await openapiTS(JSON.parse(await readFile(source, 'utf8')), {
  defaultNonNullable: true,
});
const header =
  '// Generated by `npm run gen:core` from api/openapi.draft.json. Do not edit.\n' +
  '// `npm run gen:check` fails when this file drifts from the contract.\n\n';
const generated = header + astToString(ast);

if (check) {
  const committed = await readFile(target, 'utf8').catch(() => '');
  if (committed !== generated) {
    console.error(`${fileURLToPath(target)} is out of date. Run \`npm run gen:core\` and commit it.`);
    process.exit(1);
  }
  console.log('gen:core: core-openapi.ts matches api/openapi.draft.json');
} else {
  await writeFile(target, generated);
  console.log(`gen:core: wrote ${fileURLToPath(target)}`);
}
