//! The email outbox and per-person preferences (NOTIFY1), mirroring the
//! webhook delivery discipline: fan-out records rows idempotently, a
//! worker claims due rows under a generation-fenced lease, sends with no
//! store transaction open, and completes the attempt atomically. A crash
//! after the provider accepted resends the same message (at least once).
use super::EmailPreference;
use crate::StoreError;
use crate::catalog::TenantScope;
use runbook_model::{ExecutionId, UserId};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::future::Future;

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum EmailState {
    /// Due to send (subject to next_attempt_at_ms and its lease).
    Pending,
    /// Held for the recipient's daily summary.
    Digest,
    Sent,
    Failed,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct EmailRecord {
    /// `eml_…`, derived from (event, user) so retries write the same row.
    pub id: String,
    pub org_id: runbook_model::OrganizationId,
    /// Absent only for mail to someone with no account yet (invitations).
    pub user_id: Option<UserId>,
    pub email: String,
    /// The intent kind, or `invitation` / `daily_summary`.
    pub kind: String,
    pub execution_id: Option<ExecutionId>,
    /// Dedupe identity with the recipient: an intent's event id, an
    /// invitation id, or `digest:{user}:{date}`.
    pub event_id: String,
    pub subject: String,
    pub text: String,
    pub html: String,
    pub state: EmailState,
    pub attempts: u32,
    pub next_attempt_at_ms: i64,
    pub created_at_ms: i64,
    pub sent_at_ms: Option<i64>,
    pub failure: Option<String>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct EmailLease {
    pub record: EmailRecord,
    pub generation: u64,
    pub claimed_at_ms: i64,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct EmailCompletion {
    pub sent: bool,
    /// Retry time for a failed attempt; None ends it as Failed.
    pub next_attempt_at_ms: Option<i64>,
    pub failure: Option<String>,
}

/// A stored preference row's unsubscribe salt derives the link token:
/// `{user_id}.{hex(sha256(salt || user_id))}` truncated to 32 chars. The
/// salt is generated by the host (entropy is a host concern) the first
/// time a mail to the person is planned, and kept across changes, so old
/// links keep working until the salt is rotated by clearing preferences.
pub fn unsubscribe_token(salt: &str, user_id: &UserId) -> String {
    let mut hash = Sha256::new();
    hash.update(salt.as_bytes());
    hash.update(b"\n");
    hash.update(user_id.as_str().as_bytes());
    let digest = hash.finalize();
    let hex: String = digest.iter().map(|b| format!("{b:02x}")).collect();
    format!("{}.{}", user_id, &hex[..32])
}

/// True when `token` is this user's current unsubscribe token. Compared
/// on digests so neither length nor prefix leaks through timing.
pub fn unsubscribe_token_matches(salt: &str, user_id: &UserId, token: &str) -> bool {
    if salt.is_empty() {
        return false;
    }
    let expected = unsubscribe_token(salt, user_id);
    let a = Sha256::digest(expected.as_bytes());
    let b = Sha256::digest(token.as_bytes());
    let mut diff = 0u8;
    for i in 0..32 {
        diff |= a[i] ^ b[i];
    }
    diff == 0
}

/// Shared email storage. Deliveries are org-scoped for tenant isolation;
/// preferences are per person (a user belongs to one org in practice, and
/// the salt/token must not multiply per org). Implementations keep each
/// call atomic; futures need not be Send.
pub trait NotifyStore {
    fn notify_time_ms(&self) -> impl Future<Output = Result<i64, StoreError>>;
    /// The person's preference and unsubscribe salt, if a row exists.
    fn email_preference(
        &self,
        user_id: &UserId,
    ) -> impl Future<Output = Result<Option<(EmailPreference, Option<String>)>, StoreError>>;
    /// Set the preference, keeping any existing salt.
    fn set_email_preference(
        &self,
        user_id: &UserId,
        preference: EmailPreference,
    ) -> impl Future<Output = Result<(), StoreError>>;
    /// The stored salt, inserting `candidate` (host entropy) when absent.
    fn ensure_unsubscribe_salt(
        &self,
        user_id: &UserId,
        candidate: String,
    ) -> impl Future<Output = Result<String, StoreError>>;
    /// Insert rows that are new on (event_id, user_id); returns how many.
    fn record_emails(
        &self,
        records: Vec<EmailRecord>,
    ) -> impl Future<Output = Result<usize, StoreError>>;
    /// Due Pending rows not currently leased, generation-fenced.
    fn claim_emails(
        &self,
        limit: usize,
        lease_ms: u64,
    ) -> impl Future<Output = Result<Vec<EmailLease>, StoreError>>;
    fn complete_email(
        &self,
        id: &str,
        generation: u64,
        completion: EmailCompletion,
    ) -> impl Future<Output = Result<(), StoreError>>;
    /// Digest rows created strictly before `before_ms`, oldest first.
    fn claim_digest(
        &self,
        before_ms: i64,
        limit: usize,
        lease_ms: u64,
    ) -> impl Future<Output = Result<Vec<EmailLease>, StoreError>>;
    /// SLACK1: the project's incoming-webhook URL, if configured. The
    /// URL is a credential: reads exist for posting and settings checks,
    /// and it is never returned by an API or logged.
    fn slack_url(
        &self,
        scope: &TenantScope,
    ) -> impl Future<Output = Result<Option<String>, StoreError>>;
    fn set_slack_url(
        &self,
        scope: &TenantScope,
        url: Option<String>,
    ) -> impl Future<Output = Result<(), StoreError>>;
    /// Mark digested rows sent (they went out inside a summary mail).
    fn mark_digested(
        &self,
        ids: Vec<(String, u64)>,
        at_ms: i64,
    ) -> impl Future<Output = Result<(), StoreError>>;
}
