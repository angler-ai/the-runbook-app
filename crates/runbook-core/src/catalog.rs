//! Tenant-bound draft and derived catalog reads. Execution state remains authoritative.
use crate::{CommitResult, StoreError};
use runbook_model::{
    ExecutionId, ExecutionStatus, OrganizationId, ProjectId, RecipientRef, RunbookId, StepRunId,
};
use serde::{Deserialize, Serialize};
use std::future::Future;
pub(crate) mod data;

#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub struct TenantScope {
    pub org_id: OrganizationId,
    pub project_id: ProjectId,
}
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct DraftRevision {
    pub key: String,
    pub revision: u64,
    pub source: String,
}
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct RunSummary {
    pub execution_id: ExecutionId,
    pub runbook_id: RunbookId,
    pub sequence: u64,
    pub status: ExecutionStatus,
    pub completed_at_ms: Option<i64>,
    /// Search projection (B3.3/D22): rendered title, tags, indexed custom
    /// fields only, and creation actor/time. Exact payloads stay in body.
    #[serde(default)]
    pub title: String,
    #[serde(default)]
    pub tags: Vec<String>,
    #[serde(default, with = "runbook_spec::stored_data")]
    pub fields: runbook_model::Data,
    #[serde(default)]
    pub created_by: String,
    #[serde(default)]
    pub created_at_ms: i64,
}
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AssignmentKind {
    #[default]
    Work,
    Approval,
    Handoff,
}
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Assignment {
    pub execution_id: ExecutionId,
    pub step_run_id: StepRunId,
    pub recipients: Vec<RecipientRef>,
    /// Inbox classification and ordering facts (B8f); defaulted so older
    /// stored bodies still decode.
    #[serde(default)]
    pub kind: AssignmentKind,
    #[serde(default)]
    pub sequence: u64,
    #[serde(default)]
    pub updated_at_ms: i64,
    /// Humans who already voted on an open approval; the inbox hides it
    /// from them even when a team still lists them (R18b).
    #[serde(default)]
    pub voted_by: Vec<runbook_model::UserId>,
    /// Step path and title for inbox summaries (never instructions).
    #[serde(default)]
    pub path: String,
    #[serde(default)]
    pub title: String,
}
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct DerivedUpdate {
    pub summary: RunSummary,
    pub assignments: Vec<Assignment>,
    pub release_concurrency: bool,
    /// D40 memory proposals recorded at or before this sequence. Applied
    /// idempotently by (execution, proposal sequence), independent of the
    /// summary's own sequence check.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub memory: Vec<crate::memory_entries::MemoryProposal>,
}
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum AdmissionState {
    Admitted,
    Queued,
    Released,
}
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Admission {
    pub execution_id: ExecutionId,
    pub state: AdmissionState,
    /// Store-clock time the run was admitted (D24); its deadline anchor.
    #[serde(default)]
    pub admitted_at_ms: Option<i64>,
}
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct AdmitRequest {
    pub execution_id: ExecutionId,
    pub key: String,
    pub limit: u32,
    pub idempotency_key: String,
}

/// Where a runbook's drafts are authored. Git-managed runbooks reject
/// draft writes and draft publication (sync owns them).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RunbookOrigin {
    Ui,
    Git,
}

/// Stable runbook identity inside one project. The slug is fixed at
/// creation (D23); IDs are host-supplied, never generated by the store.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct RunbookRecord {
    pub runbook_id: runbook_model::RunbookId,
    pub slug: String,
    pub origin: RunbookOrigin,
    pub archived: bool,
}

/// One stored version row: a published number or a preview, with the exact
/// source and the semantic hash and snapshot byte digest it recorded (D21).
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct VersionRecord {
    pub version_id: runbook_model::VersionId,
    pub number: Option<std::num::NonZeroU32>,
    pub branch: Option<String>,
    pub commit_sha: Option<String>,
    pub semantic_hash: [u8; 32],
    pub snapshot_digest: [u8; 32],
    pub snapshot_size: u64,
    pub source: String,
    pub pins: crate::publish::SelectedPins,
}
impl VersionRecord {
    pub fn view(&self, runbook_id: &runbook_model::RunbookId) -> runbook_model::VersionView {
        runbook_model::VersionView {
            runbook_id: runbook_id.clone(),
            runbook_version_id: self.version_id.clone(),
            runbook_version: self.number,
            branch: self.branch.clone(),
            commit_sha: self.commit_sha.clone(),
        }
    }
}

/// Where a skill version came from. `reference` is the addressable target
/// string it was uploaded for (for example a local alias `./skills/x`),
/// when that differs from `skill://<name>`; `label` is human provenance.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct SkillProvenance {
    pub reference: Option<String>,
    pub label: String,
}

/// One immutable skill version in a project library: content-addressed by
/// folder hash, identified in the library by its front-matter name.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct SkillVersion {
    pub name: String,
    pub description: String,
    pub hash: [u8; 32],
    pub manifest: crate::skills::SkillManifest,
    pub provenance: SkillProvenance,
}

/// The catalog records belonging to one execution, including its admission token.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct RunCatalogSlice {
    pub summary: Option<RunSummary>,
    pub assignments: Vec<Assignment>,
    pub admission: Option<(AdmitRequest, Admission)>,
}

/// Handles bind a tenant at construction. Futures need not be Send.
pub trait CatalogStore {
    fn read_draft(
        &self,
        key: &str,
    ) -> impl Future<Output = Result<Option<DraftRevision>, StoreError>>;
    fn replace_draft(
        &self,
        key: &str,
        expected: u64,
        source: String,
    ) -> impl Future<Output = Result<CommitResult, StoreError>>;
    fn list_runs(&self) -> impl Future<Output = Result<Vec<RunSummary>, StoreError>>;
    fn get_run(
        &self,
        execution_id: &ExecutionId,
    ) -> impl Future<Output = Result<Option<RunSummary>, StoreError>>;
    fn list_assignments(&self) -> impl Future<Output = Result<Vec<Assignment>, StoreError>>;
    fn admit(&self, request: AdmitRequest) -> impl Future<Output = Result<Admission, StoreError>>;
    fn admission(
        &self,
        execution_id: &ExecutionId,
    ) -> impl Future<Output = Result<Option<Admission>, StoreError>>;
    /// LANG3: the runs holding or waiting for `key` in this project, holders
    /// first, then waiters in FIFO order. An unlocked read; the start
    /// transaction re-reads it under the pool lock.
    fn admission_pool(
        &self,
        key: &str,
    ) -> impl Future<Output = Result<crate::concurrency::PoolView, StoreError>>;
    /// Create runbook identity with its first draft revision; zero versions.
    fn create_runbook(
        &self,
        record: RunbookRecord,
        source: String,
    ) -> impl Future<Output = Result<runbook_model::DraftView, StoreError>>;
    fn read_runbook(
        &self,
        runbook_id: &runbook_model::RunbookId,
    ) -> impl Future<Output = Result<Option<RunbookRecord>, StoreError>>;
    fn get_draft(
        &self,
        runbook_id: &runbook_model::RunbookId,
    ) -> impl Future<Output = Result<Option<runbook_model::DraftView>, StoreError>>;
    /// Revision-guarded verbatim source save (D23: validity is not checked).
    fn save_draft(
        &self,
        runbook_id: &runbook_model::RunbookId,
        expected_revision: u64,
        source: String,
    ) -> impl Future<Output = Result<CommitResult, StoreError>>;
    /// Short numbering transaction: rechecks draft revision/source and Git
    /// ownership, returns the latest version for a semantic duplicate.
    fn publish_revision(
        &self,
        runbook_id: &runbook_model::RunbookId,
        expected_revision: u64,
        prepared: crate::publish::PreparedPublication,
    ) -> impl Future<Output = Result<runbook_model::PublishedVersionView, StoreError>>;
    fn create_preview(
        &self,
        runbook_id: &runbook_model::RunbookId,
        prepared: crate::publish::PreparedPublication,
        branch: Option<String>,
        commit_sha: Option<String>,
    ) -> impl Future<Output = Result<runbook_model::VersionView, StoreError>>;
    /// Git sync (2026-11-17): the runbook becomes Git-managed (and not
    /// archived), its draft becomes the file's source, and that source is
    /// published as the next numbered version recording the branch and
    /// commit. A semantic duplicate of the latest version returns it, with
    /// no new version and no event, as [`Self::publish_revision`] does.
    fn publish_git(
        &self,
        runbook_id: &runbook_model::RunbookId,
        prepared: crate::publish::PreparedPublication,
        branch: Option<String>,
        commit_sha: Option<String>,
    ) -> impl Future<Output = Result<runbook_model::PublishedVersionView, StoreError>>;
    /// Git sync: archive a Git-managed runbook whose file is gone (its
    /// versions and runs are kept). A UI-authored runbook is refused with
    /// `runbook.not_git_managed`.
    fn archive_git(
        &self,
        runbook_id: &runbook_model::RunbookId,
    ) -> impl Future<Output = Result<(), StoreError>>;
    /// Git sync: make a Git-managed runbook editable in the app again (its
    /// draft and versions stay; the next sync of its file adopts it back).
    fn detach_git(
        &self,
        runbook_id: &runbook_model::RunbookId,
    ) -> impl Future<Output = Result<(), StoreError>>;
    /// Omitted selector: highest published number. Foreign and nonexistent
    /// versions are the same NotFound.
    fn resolve_version(
        &self,
        runbook_id: &runbook_model::RunbookId,
        selector: Option<runbook_model::VersionSelector>,
    ) -> impl Future<Output = Result<runbook_model::VersionView, StoreError>>;
    fn version_record(
        &self,
        runbook_id: &runbook_model::RunbookId,
        version_id: &runbook_model::VersionId,
    ) -> impl Future<Output = Result<Option<VersionRecord>, StoreError>>;
    fn list_versions(
        &self,
        runbook_id: &runbook_model::RunbookId,
    ) -> impl Future<Output = Result<Vec<runbook_model::PublishedVersionView>, StoreError>>;
    fn list_previews(
        &self,
        runbook_id: &runbook_model::RunbookId,
    ) -> impl Future<Output = Result<Vec<runbook_model::VersionView>, StoreError>>;
    /// Record an immutable skill version, or return the existing record
    /// for the same name and folder hash. New hashes become latest.
    fn record_skill_version(
        &self,
        version: SkillVersion,
    ) -> impl Future<Output = Result<SkillVersion, StoreError>>;
    fn skill_version(
        &self,
        hash: &[u8; 32],
    ) -> impl Future<Output = Result<Option<SkillVersion>, StoreError>>;
    /// The latest recorded version of every skill name in this project.
    fn latest_skills(&self) -> impl Future<Output = Result<Vec<SkillVersion>, StoreError>>;
    /// Stored runbook versions whose selected pins include this skill hash.
    fn versions_pinning_skill(
        &self,
        hash: &[u8; 32],
    ) -> impl Future<Output = Result<Vec<(runbook_model::RunbookId, VersionRecord)>, StoreError>>;
    /// D22 search over this tenant's run summaries: newest first, then
    /// execution ID; the cursor is bound to scope and filters.
    /// Org-scoped key read for routing (never grants access): which
    /// project in this organization owns the execution, if any.
    fn execution_project(
        &self,
        org_id: &runbook_model::OrganizationId,
        execution_id: &ExecutionId,
    ) -> impl Future<Output = Result<Option<runbook_model::ProjectId>, StoreError>>;
    /// Org-scoped routing read for a deleted run: retention removes the
    /// owner row, so routes resolve tombstones separately for 410s.
    fn tombstone_project(
        &self,
        org_id: &runbook_model::OrganizationId,
        execution_id: &ExecutionId,
    ) -> impl Future<Output = Result<Option<runbook_model::ProjectId>, StoreError>>;
    fn search_runs(
        &self,
        filters: crate::search::RunFilters,
        cursor: Option<String>,
        limit: usize,
    ) -> impl Future<Output = Result<crate::search::RunPage, StoreError>>;
    /// UI-1: for each of these runbooks (in this project), its newest run
    /// and its active runs ([`crate::search::ACTIVE_STATUSES`]), counting at
    /// most `active_cap`. Every requested ID is in the result; one without
    /// runs (or not in this project) has the default. The SQL adapters
    /// answer a whole list page in one query over their
    /// `run_summary (runbook_id, created_at_ms DESC, execution_id DESC)`
    /// and partial active-status indexes; this default reads
    /// [`Self::search_runs`] twice per ID.
    fn runbook_run_stats(
        &self,
        runbook_ids: &[runbook_model::RunbookId],
        active_cap: usize,
    ) -> impl Future<
        Output = Result<
            std::collections::BTreeMap<runbook_model::RunbookId, crate::search::RunbookRunStats>,
            StoreError,
        >,
    > {
        async move {
            let mut out = std::collections::BTreeMap::new();
            for id in runbook_ids {
                let filters = crate::search::RunFilters {
                    runbook_id: Some(id.clone()),
                    ..Default::default()
                };
                let last_run = self.search_runs(filters.clone(), None, 1).await?.runs.pop();
                let active_runs = if active_cap == 0 {
                    0
                } else {
                    self.search_runs(
                        crate::search::RunFilters {
                            statuses: crate::search::ACTIVE_STATUSES.to_vec(),
                            ..filters
                        },
                        None,
                        active_cap,
                    )
                    .await?
                    .runs
                    .len()
                };
                out.insert(
                    id.clone(),
                    crate::search::RunbookRunStats {
                        last_run,
                        active_runs,
                    },
                );
            }
            Ok(out)
        }
    }
}
