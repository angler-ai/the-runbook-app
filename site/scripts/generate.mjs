#!/usr/bin/env node
// Generates the reference pages under src/content/docs/reference/ from the
// code, so they can't drift from what ships (DOCS1):
//
// - cli.md and mcp.md from `runbook __docs-reference`, which dumps the CLI's
//   clap definitions and runbook-mcp's tool, resource and prompt definitions;
// - environment.md from deploy/.env.example (the documented settings) plus
//   every RUNBOOK_* / DATABASE_* name the server's source reads.
//
// The CLI comes from `cargo run -p runbook-cli`, or from RUNBOOK_BIN when set
// (CI can point it at a binary it already built). `npm run check:generated`
// regenerates and fails when the committed pages differ.
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { basename, dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(site, '..');
const outDir = join(site, 'src/content/docs/reference');

function loadReference() {
  const opts = { cwd: repo, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 };
  const out = process.env.RUNBOOK_BIN
    ? execFileSync(resolve(process.env.RUNBOOK_BIN), ['__docs-reference'], opts)
    : execFileSync('cargo', ['run', '-q', '--locked', '-p', 'runbook-cli', '--', '__docs-reference'], {
        ...opts,
        stdio: ['ignore', 'pipe', 'inherit'],
      });
  return JSON.parse(out);
}

const banner = (source) =>
  `{/* Generated by site/scripts/generate.mjs from ${source}. Do not edit; run \`npm run generate\` in site/. */}\n`;

// Text outside code: keep Markdown/MDX from reading <, {, } as markup.
const esc = (s) => String(s ?? '').replace(/[<>{}]/g, (c) => `&#${c.charCodeAt(0)};`);
const oneLine = (s) => esc(s).replace(/\s*\n\s*/g, ' ').trim();
const code = (s) => '`' + String(s).replace(/`/g, '\\`') + '`';
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

function frontmatter(title, description) {
  return `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\n---\n\n`;
}

// ---------------------------------------------------------------- CLI ----

function usage(cmd) {
  const parts = [cmd.path];
  for (const a of cmd.args) {
    if (a.global) continue;
    if (a.positional) {
      const v = a.value_names.join(' ') + (a.multiple ? '...' : '');
      parts.push(a.required ? `<${v}>` : `[${v}]`);
    }
  }
  if (cmd.args.some((a) => !a.positional && !a.global)) parts.push('[OPTIONS]');
  if (cmd.subcommands.length) parts.push('<COMMAND>');
  return parts.join(' ');
}

function argName(a) {
  if (a.positional) return a.value_names.join(' ') + (a.multiple ? '...' : '');
  const flag = [a.short && `-${a.short}`, a.long && `--${a.long}`].filter(Boolean).join(', ');
  return a.takes_value ? `${flag} <${a.value_names.join(' ')}>` : flag;
}

function argDetails(a) {
  const bits = [];
  if (a.help) bits.push(oneLine(a.help));
  if (a.required) bits.push('Required.');
  if (a.multiple && !a.positional) bits.push('Repeatable.');
  if (a.possible_values.length) bits.push(`One of ${a.possible_values.map(code).join(', ')}.`);
  if (a.default.length) bits.push(`Default ${a.default.map(code).join(', ')}.`);
  if (a.env) bits.push(`Environment: ${code(a.env)}.`);
  return bits.join(' ');
}

function renderCommand(cmd, depth, lines) {
  const h = '#'.repeat(Math.min(depth, 6));
  lines.push(`${h} ${code(cmd.path)}`, '');
  if (cmd.about) lines.push(esc(cmd.about.trim()), '');
  if (cmd.long_about && cmd.long_about !== cmd.about) lines.push(esc(cmd.long_about.trim()), '');
  if (cmd.aliases.length) lines.push(`Aliases: ${cmd.aliases.map(code).join(', ')}.`, '');
  lines.push('```text', usage(cmd), '```', '');
  const args = cmd.args.filter((a) => !a.global);
  const positional = args.filter((a) => a.positional);
  const options = args.filter((a) => !a.positional);
  for (const [label, list] of [
    ['Arguments', positional],
    ['Options', options],
  ]) {
    if (!list.length) continue;
    lines.push(`**${label}**`, '');
    for (const a of list) {
      const d = argDetails(a);
      lines.push(`- ${code(argName(a))}${d ? `: ${d}` : ''}`);
    }
    lines.push('');
  }
  if (cmd.subcommands.length) {
    lines.push('**Commands**', '');
    for (const s of cmd.subcommands) {
      lines.push(`- [${code(s.name)}](#${slug(s.path)}): ${oneLine(s.about ?? '')}`);
    }
    lines.push('');
  }
  for (const s of cmd.subcommands) renderCommand(s, depth + 1, lines);
}

function renderCli(cli) {
  const lines = [
    frontmatter('CLI reference', 'Every command and flag of the runbook CLI, generated from its clap definitions.'),
    banner('the CLI\'s clap definitions (crates/runbook-cli)'),
    'Every command and flag of the `runbook` CLI, generated from its own',
    'definitions. Run `runbook <command> --help` for the same text in a',
    'terminal.',
    '',
    '## Global options',
    '',
    'These work with every command.',
    '',
  ];
  for (const a of cli.args.filter((a) => a.global)) {
    const d = argDetails(a);
    lines.push(`- ${code(argName(a))}${d ? `: ${d}` : ''}`);
  }
  lines.push('', '## Commands', '');
  for (const s of cli.subcommands) {
    lines.push(`- [${code(s.name)}](#${slug(s.path)}): ${oneLine(s.about ?? '')}`);
  }
  lines.push('');
  for (const s of cli.subcommands) renderCommand(s, 2, lines);
  return lines.join('\n').replace(/\n{3,}/g, '\n\n');
}

// ---------------------------------------------------------------- MCP ----

function schemaType(p) {
  if (!p) return '';
  if (p.enum) return p.enum.map((v) => JSON.stringify(v)).join(' \\| ');
  if (Array.isArray(p.type)) return p.type.join(' \\| ');
  if (p.type === 'array') return `array of ${schemaType(p.items) || 'any'}`;
  if (p.type) return p.type;
  if (p.oneOf || p.anyOf) return (p.oneOf || p.anyOf).map(schemaType).join(' \\| ');
  return 'any';
}

const cell = (s) => oneLine(s).replace(/\|/g, '\\|');

function renderMcp(mcp) {
  const lines = [
    frontmatter('MCP reference', 'Every tool, resource and prompt of the Runbook MCP server, generated from its definitions.'),
    banner('the MCP server\'s definitions (crates/runbook-mcp)'),
    'The same tools, resources and prompts are served locally over stdio',
    '(`runbook mcp serve`) and remotely at `/mcp` with OAuth sign-in.',
    '',
    '## Tools',
    '',
  ];
  const tools = [...mcp.tools].sort((a, b) => a.name.localeCompare(b.name));
  lines.push('| Tool | What it does |', '| --- | --- |');
  for (const t of tools) lines.push(`| [${code(t.name)}](#${slug(t.name)}) | ${cell(t.description)} |`);
  lines.push('');
  for (const t of tools) {
    lines.push(`### ${code(t.name)}`, '', esc(t.description), '');
    const hints = t.annotations ?? {};
    const flags = [
      hints.readOnlyHint && 'read-only',
      hints.destructiveHint && 'destructive',
      hints.idempotentHint && 'idempotent',
      hints.openWorldHint && 'open world',
    ].filter(Boolean);
    if (flags.length) lines.push(`Hints: ${flags.join(', ')}.`, '');
    const props = t.inputSchema?.properties ?? {};
    const required = new Set(t.inputSchema?.required ?? []);
    const names = Object.keys(props);
    if (names.length) {
      lines.push('| Argument | Type | Required | Description |', '| --- | --- | --- | --- |');
      for (const n of names) {
        const p = props[n];
        lines.push(`| ${code(n)} | ${cell(schemaType(p))} | ${required.has(n) ? 'yes' : ''} | ${cell(p.description ?? '')} |`);
      }
      lines.push('');
    } else {
      lines.push('No arguments.', '');
    }
  }
  lines.push('## Resources', '');
  for (const r of mcp.resource_templates.resourceTemplates ?? []) {
    lines.push(`### ${esc(r.title ?? r.name)}`, '', `${code(r.uriTemplate)} (${code(r.mimeType)})`, '', esc(r.description), '');
  }
  lines.push('## Prompts', '');
  for (const p of mcp.prompts.prompts ?? []) {
    lines.push(`### ${code(p.name)}`, '', esc(p.description), '');
    if (p.arguments?.length) {
      lines.push('| Argument | Required | Description |', '| --- | --- | --- |');
      for (const a of p.arguments) lines.push(`| ${code(a.name)} | ${a.required ? 'yes' : ''} | ${cell(a.description)} |`);
      lines.push('');
    }
  }
  return lines.join('\n').replace(/\n{3,}/g, '\n\n');
}

// -------------------------------------------------------- Environment ----

function parseEnvExample(text) {
  const sections = [];
  let current = { title: 'General', vars: [] };
  let comments = [];
  for (const raw of text.split('\n')) {
    const line = raw.trimEnd();
    const header = line.match(/^# --- (.+?) -*$/);
    if (header) {
      if (current.vars.length) sections.push(current);
      current = { title: header[1], vars: [] };
      comments = [];
      continue;
    }
    const v = line.match(/^#?\s*([A-Z][A-Z0-9_]+)=(\S*)\s*(?:#\s*(.*))?$/);
    if (v) {
      const [, name, value, trailing] = v;
      const exampleOnly = line.startsWith('#');
      const existing = current.vars.find((x) => x.name === name);
      if (existing) continue;
      const desc = [...comments.map((c) => c.trim()), trailing].filter(Boolean).join(' ');
      current.vars.push({ name, value: exampleOnly ? '' : value, desc });
      if (!exampleOnly || trailing) comments = [];
      continue;
    }
    if (line.startsWith('#')) comments.push(line.replace(/^# ?/, ''));
    else comments = [];
  }
  if (current.vars.length) sections.push(current);
  return sections.filter((s) => !/^Copy to/.test(s.title));
}

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (p.endsWith('.rs')) out.push(p);
  }
  return out;
}

function serverEnvNames() {
  const dirs = readdirSync(join(repo, 'crates'))
    .filter((d) => d === 'runbook-server' || d.startsWith('runbook-store-'))
    .map((d) => join(repo, 'crates', d, 'src'));
  const found = new Map();
  for (const file of dirs.flatMap((d) => walk(d))) {
    const src = readFileSync(file, 'utf8').split(/#\[cfg\(test\)\]/)[0];
    for (const m of src.matchAll(/"((?:RUNBOOK|DATABASE)_[A-Z0-9_]+)"/g)) {
      if (/_TEST_|CAPTURE/.test(m[1])) continue;
      if (!found.has(m[1])) found.set(m[1], relative(repo, file));
    }
  }
  return found;
}

function renderEnv() {
  const example = readFileSync(join(repo, 'deploy/.env.example'), 'utf8');
  const sections = parseEnvExample(example);
  const documented = new Set(sections.flatMap((s) => s.vars.map((v) => v.name)));
  const lines = [
    frontmatter('Environment variables', 'Every setting of the container edition, generated from deploy/.env.example and the server source.'),
    banner('deploy/.env.example and the server\'s source'),
    ':::note[Docker/Kubernetes]',
    'These are the container edition\'s settings. The Cloudflare edition is',
    'configured in `wrangler.jsonc` and with `wrangler secret put`; see',
    '[the Cloudflare quick start](/getting-started/cloudflare/).',
    ':::',
    '',
    'All configuration is environment; nothing is baked into the image. Copy',
    '`deploy/.env.example` to `deploy/.env` and fill it in.',
    '',
  ];
  for (const s of sections) {
    lines.push(`## ${esc(s.title)}`, '', '| Variable | Example | Description |', '| --- | --- | --- |');
    for (const v of s.vars) lines.push(`| ${code(v.name)} | ${v.value ? code(v.value) : ''} | ${cell(v.desc)} |`);
    lines.push('');
  }
  const more = [...serverEnvNames()].filter(([n]) => !documented.has(n)).sort(([a], [b]) => a.localeCompare(b));
  if (more.length) {
    lines.push(
      '## Also read by the server',
      '',
      'These are read by the server but aren\'t in `deploy/.env.example`.',
      'The [install guide](https://github.com/angler-ai/the-runbook-app/blob/main/docs/install.md)',
      'describes most of them.',
      '',
      '| Variable | Read in |',
      '| --- | --- |',
    );
    for (const [n, f] of more) lines.push(`| ${code(n)} | ${code(f)} |`);
    lines.push('');
  }
  return lines.join('\n').replace(/\n{3,}/g, '\n\n');
}

// ------------------------------------------------------------ Samples ----

// The gallery: the seeded review runbooks, copied verbatim into one page each.
export const SAMPLES_DIR = join(repo, 'scripts/dev/review-runbooks');

export function sampleFiles() {
  return readdirSync(SAMPLES_DIR)
    .filter((f) => f.endsWith('.yaml'))
    .sort()
    .map((f) => join(SAMPLES_DIR, f));
}

function metadataField(src, key) {
  const m = src.match(new RegExp(`^  ${key}: (.+)$`, 'm'));
  if (!m) return '';
  const v = m[1].trim();
  return v.startsWith('"') ? JSON.parse(v) : v;
}

function renderSample(file) {
  const src = readFileSync(file, 'utf8');
  const id = metadataField(src, 'id');
  const title = metadataField(src, 'title') || id;
  const description = metadataField(src, 'description') || `The ${id} runbook.`;
  const rel = relative(repo, file);
  return [
    frontmatter(title, description),
    banner(rel),
    `${esc(description)}`,
    '',
    `Source: ${code(rel)}. CI checks it with \`runbook spec validate\`; teams,`,
    'people, skills and called runbooks it names resolve against your server',
    'when you publish it.',
    '',
    '```yaml',
    src.trimEnd(),
    '```',
    '',
    'Publish it to a project:',
    '',
    '```sh',
    `runbook push ${id}.yaml --project <project> --draft`,
    `runbook publish ${id} --project <project>`,
    '```',
    '',
  ].join('\n');
}

// ---------------------------------------------------------------- main ----

if (process.argv[1] !== fileURLToPath(import.meta.url)) {
  // Imported (validate-samples.mjs uses sampleFiles); generate nothing.
} else {
const ref = loadReference();
mkdirSync(outDir, { recursive: true });
const pages = {
  'cli.mdx': renderCli(ref.cli),
  'mcp.mdx': renderMcp(ref.mcp),
  'environment.mdx': renderEnv(),
};
for (const [name, body] of Object.entries(pages)) {
  writeFileSync(join(outDir, name), body);
  console.log(`wrote ${relative(repo, join(outDir, name))}`);
}
// The changelog: docs/release-notes.md, without its own heading.
const notes = readFileSync(join(repo, 'docs/release-notes.md'), 'utf8').replace(/^# .*\n/, '');
const changelogDir = join(site, 'src/content/docs/changelog');
mkdirSync(changelogDir, { recursive: true });
writeFileSync(
  join(changelogDir, 'index.md'),
  frontmatter('Release notes', 'Changes an operator should read before updating, newest first.') +
    '<!-- Generated by site/scripts/generate.mjs from docs/release-notes.md. Do not edit. -->\n' +
    notes,
);
console.log('wrote site/src/content/docs/changelog/index.md');
const samplesDir = join(site, 'src/content/docs/samples');
mkdirSync(samplesDir, { recursive: true });
for (const file of sampleFiles()) {
  const out = join(samplesDir, basename(file, '.yaml') + '.mdx');
  writeFileSync(out, renderSample(file));
  console.log(`wrote ${relative(repo, out)}`);
}
}
